#!/usr/bin/env python
"""Turn a `scripts/audit-normal-maps.py` JSON into `src/vrscan/normal_pins.py`:
fingerprint -> the rule the audit established for that map (design review
22.09 A1). Runs anywhere — the audit JSON carries hashes and numbers only,
never a pixel.

    uv run python scripts/make-normal-pins.py scratch/audit-normal-maps.json

A map is pinned only when the decoder path itself shows its encoding, not
when its statistics suggest one:
- the backend's RGBA equals an independent BC3 decode byte for byte
  (`reference.identical`), so the channels are the stored ones;
- R and B are per-texel copies of G (mean |R-G|, |B-G| within RGB565
  rounding) — Unity's DXT5nm packing, where X lives only in alpha. That
  gives "ag" with Z rebuilt from X and Y.
Anything else is reported on stderr and left out: it falls back to its
profile's rule as "unverified" at convert time.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "vrscan" / "normal_pins.py"
MAX_MEAN_COPY_DIFF = 2.0  # 8-bit steps; the audited maps are at most 1.2
MAX_COPY_DIFF = 16  # RGB565 endpoint rounding alone reaches ~8, the audited maps 12
DXT5NM_RULE = "ag-reconstruct"


def _rule_for(row: dict) -> str | None:
    if row.get("unityFormat") != "DXT5" or not row.get("reference", {}).get("identical"):
        return None
    copies = row.get("rgbCopies", {})
    for channel in ("r", "b"):
        stats = copies.get(channel, {})
        if stats.get("mean", 255) > MAX_MEAN_COPY_DIFF or stats.get("max", 255) > MAX_COPY_DIFF:
            return None
    return DXT5NM_RULE


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("audit_json", nargs="+")
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args()

    pins: dict[str, tuple[str, set[str]]] = {}
    datasets: list[str] = []
    audited = 0
    for path in args.audit_json:
        audit = json.loads(Path(path).read_text(encoding="utf-8"))
        for dataset in audit["datasets"]:
            datasets.append(dataset["dataset"])
            for row in dataset["rows"]:
                audited += 1
                fingerprint, rule = row.get("fingerprint"), _rule_for(row)
                if fingerprint is None or rule is None:
                    print(f"not pinned: {dataset['dataset']} {row.get('texture')}", file=sys.stderr)
                    continue
                known_rule, kinds = pins.setdefault(fingerprint, (rule, set()))
                if known_rule != rule:
                    raise SystemExit(f"{fingerprint}: audited as both {known_rule} and {rule}")
                kinds.update(row.get("kinds") or ())

    lines = [
        '"""Normal maps whose encoding an audit established, by content fingerprint',
        "(`reader/backend.texture_fingerprint`) — generated by",
        "`scripts/make-normal-pins.py` from `scripts/audit-normal-maps.py` output;",
        "do not edit by hand. Hashes and part kinds only, no pixel data.",
        "",
        "`AUDIT` describes where the audit ran; it is not a condition on which",
        'datasets the pins apply to — a map with the same fingerprint is the same map."""',
        "",
        "from __future__ import annotations",
        "",
        "from vrscan.profiles import NormalRule",
        "",
        f"AUDIT = {json.dumps(f'audit-normal-maps 22.09: {audited} maps of {len(datasets)} datasets')}",
        f"AUDIT_DATASETS = {tuple(datasets)!r}",
        "",
        "# fingerprint -> (rule key, part kinds whose exported material used the map",
        "# during the audit; empty = a scene prop no exported part carries)",
        "VERIFIED_NORMAL_MAPS: dict[str, tuple[str, tuple[str, ...]]] = {",
    ]
    for fingerprint, (rule, kinds) in sorted(pins.items()):
        lines.append(f'    "{fingerprint}": ("{rule}", {tuple(sorted(kinds))!r}),')
    lines += [
        "}",
        "",
        "",
        "def verified_rules() -> dict[str, NormalRule]:",
        "    return {fp: NormalRule.from_key(rule) for fp, (rule, _kinds) in VERIFIED_NORMAL_MAPS.items()}",
        "",
    ]
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}: {len(pins)} fingerprints from {audited} audited maps", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
